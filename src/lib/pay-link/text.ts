/**
 * Тексты, которые задаёт владелец ссылки оплаты — то есть, возможно, нападающий
 * (задание, § 2.8). Имя магазина, название ссылки и символ монеты приходят от службы
 * как есть и показываются покупателю и владельцу карточки.
 *
 * Чистим три разных вида знаков, и путать их нельзя:
 *
 * - **управляющие** — не текст для показа вовсе (прецедент `CONTROL` в `donations.ts`);
 * - **bidi** (U+202A–202E, U+2066–2069) — переворачивают порядок строки и дают имени
 *   выглядеть другим именем прямо на экране; знак, не закрытый своей парой, уезжает в
 *   соседнюю строку интерфейса;
 * - **нулевой ширины** — делают два разных имени неразличимыми глазом.
 *
 * Разметки мы не вырезаем и не экранируем: показываем только текстом, а `<b>` в имени
 * пусть так и читается — `<b>`. Вырезать его значило бы молча менять слова владельца.
 */

/** Знаки нулевой ширины, невидимые соединители и мягкий перенос. */
const INVISIBLE = /[\u00ad\u200b-\u200f\u2060-\u2064\ufeff]/g;
/** Переопределение направления письма. */
const BIDI = /[\u202a-\u202e\u2066-\u2069]/g;
/** Управляющие знаки C0 и C1 — вместе с переводами строк: карточка не стихи. */
const CONTROL = /[\u0000-\u001f\u007f-\u009f]/g;

/** Длина показываемого текста (§ 2.8). */
export const DISPLAY_MAX = 80;
/** Длина названия ссылки, как её отдаёт служба (§ 2.2). */
export const TITLE_MAX = 200;

/**
 * Невидимое вон — и ничего больше. Нужно **до** поиска кода в названии: код, разбитый
 * знаком нулевой ширины, иначе не нашёлся бы, а человек в кабинете видел бы его целым.
 */
export function stripInvisible(text: string): string {
  return text.replace(INVISIBLE, "").replace(BIDI, "");
}

/**
 * Текст для показа: невидимое и управляющее вон, пробелы в один, обрезка до 80.
 * Обрезка последней: сперва убираем знаки, иначе восемьдесят знаков могли бы целиком
 * оказаться невидимыми, и на экране стояла бы пустая строка вместо имени.
 */
export function cleanDisplay(text: string, max = DISPLAY_MAX): string {
  return stripInvisible(text)
    .replace(CONTROL, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max);
}
