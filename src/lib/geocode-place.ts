/**
 * Что спрашивать у геокодера, когда место описано двумя полями — названием и
 * адресом (место рекламного материала, слайс BZ).
 *
 * Прежде запрос склеивался из обоих полей и уходил **один**: «ALTA Invest GmbH,
 * Brehmstraße 19, 1020 Wien» Nominatim не знает вовсе и отвечает пустым списком,
 * хотя один адрес без названия находит сразу (живая проверка 23 ноября). Для
 * человека это выглядело так, что кнопка «найти на карте» не работает: название
 * предприятия в реестре улиц есть только у знаменитых мест.
 *
 * Поэтому кандидат не один, а список по убыванию точности: сперва название с
 * адресом (у известного места оно даёт сам дом, а не улицу), затем адрес без
 * названия, затем одно название (на случай «Hotel Sacher» без адреса). Запросы
 * задаются по одному до первого непустого ответа — так же, как кириллические
 * варианты в маршруте геокодера.
 */

const MIN_QUERY = 4;

export function placeQueryOrder(name: string, address: string): string[] {
  const n = name.trim().replace(/\s+/g, " ");
  const a = address.trim().replace(/\s+/g, " ");
  const raw = [n && a ? `${n}, ${a}` : "", a, n];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const q of raw) {
    if (q.length < MIN_QUERY) continue;
    const key = q.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(q);
  }
  return out;
}
