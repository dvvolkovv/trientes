/**
 * Выбранное значение списка, когда список пришёл позже формы.
 *
 * Дефект, найденный живым прогоном BI: `useState(options[0]?.id ?? "")` запоминает
 * **пустоту** первого рендера, а `<select value="">` без совпадающей строки показывает
 * первую строку списка. На экране стоял поставщик, а действие отвечало «выберите
 * поставщика»: экран врал. Поэтому значение не берётся из состояния напрямую, а
 * сверяется со списком — и если его там нет, берётся первое.
 */
export function effectiveOption(ids: readonly string[], value: string): string {
  return ids.includes(value) ? value : (ids[0] ?? "");
}
